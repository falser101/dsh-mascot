/**
 * Convert the AI-generated art in docs/ into inlined plugin assets:
 * JPEG → flood-fill the near-white background to transparent (from the
 * corners, so the cream chest/muzzle stay) → 512px WebP → base64
 * TypeScript module (src/client/character/generated.ts). Every source frame
 * must share the same full-body framing (do not feed zoomed head close-ups).
 * Re-run whenever the art changes. Dev tool only.
 */
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const SOURCES = {
  'face-neutral': '正常脸.jpg',
  'face-happy': '开心脸.jpg',
  'face-sad': '难过脸.jpg',
  'face-thinking': '思考脸.jpg',
  'face-closed': '闭眼帧.jpg',
}

const SIZE = 512

function toWebpBase64(file) {
  const [width, height] = execSync(`identify -format '%w %h' 'docs/${file}'`, { encoding: 'utf8' })
    .trim()
    .split(' ')
    .map(Number)
  const webp = execSync(
    `magick 'docs/${file}' -alpha set -channel RGBA -fuzz 8% -fill none ` +
    `-floodfill +0+0 white ` +
    `-floodfill +${width - 1}+0 white ` +
    `-floodfill +0+${height - 1} white ` +
    `-floodfill +${width - 1}+${height - 1} white ` +
    `-resize ${SIZE}x${SIZE} -quality 80 webp:-`,
    { encoding: null, maxBuffer: 64 * 1024 * 1024 },
  )
  return webp.toString('base64')
}

const entries = {}
for (const [name, file] of Object.entries(SOURCES)) {
  const base64 = toWebpBase64(file)
  entries[name] = base64
  console.log(`${name}: ${(base64.length / 1024).toFixed(0)} KiB base64`)
}

const banner = `/**
 * GENERATED by scripts/build-art-assets.mjs — do not edit by hand.
 * AI-generated character art (docs/*.jpg) flood-filled to transparent,
 * resized to 512px, encoded as WebP, and inlined as base64 so the bundle
 * ships self-contained. Regenerate with: node scripts/build-art-assets.mjs
 */
export const CHARACTER_ASSETS: Record<string, string> = ${JSON.stringify(entries, null, 2)}
`

writeFileSync('src/client/character/generated.ts', banner)
console.log('written src/client/character/generated.ts')
