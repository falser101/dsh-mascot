/**
 * Convert the AI-generated art in docs/ into inlined plugin assets:
 * white-background JPEG → chroma-keyed transparent → 512px WebP → base64
 * TypeScript module (src/client/character/generated.ts). Re-run whenever the
 * art changes; the generated module is committed (it ships inside the bundle).
 * Dev tool only.
 */
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { readdirSync } from 'node:fs'

const SOURCES = {
  body: '主形象图.jpg',
  'face-neutral': '正常脸.jpg',
  'face-happy': '开心脸.jpg',
  'face-sad': '难过脸.jpg',
  'face-thinking': '思考脸.jpg',
  'face-closed': '闭眼帧.jpg',
}

const SIZE = 512

function toWebpBase64(file, keyColor) {
  const webp = execSync(
    `ffmpeg -v error -y -i 'docs/${file}' -vf ` +
    `"colorkey=${keyColor}:similarity=0.10:blend=0.12,format=rgba,scale=${SIZE}:${SIZE}:flags=lanczos" ` +
    `-frames:v 1 -c:v libwebp -quality 80 -f webp pipe:`,
    { encoding: null, maxBuffer: 64 * 1024 * 1024 },
  )
  return webp.toString('base64')
}

const entries = {}
for (const [name, file] of Object.entries(SOURCES)) {
  const base64 = toWebpBase64(file, '0xFFFFFF')
  entries[name] = base64
  console.log(`${name}: ${(base64.length / 1024).toFixed(0)} KiB base64`)
}

const banner = `/**
 * GENERATED by scripts/build-art-assets.mjs — do not edit by hand.
 * AI-generated character art (docs/*.jpg) chroma-keyed to transparent,
 * resized to 512px, encoded as WebP, and inlined as base64 so the bundle
 * ships self-contained. Regenerate with: node scripts/build-art-assets.mjs
 */
export const CHARACTER_ASSETS: Record<string, string> = ${JSON.stringify(entries, null, 2)}
`

writeFileSync('src/client/character/generated.ts', banner)
console.log('written src/client/character/generated.ts')
